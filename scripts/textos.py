ALL = {**TEXTOS}
for key in TEXTOS_ESTUDIO:
    if key in ALL:
        raise SystemExit(f"Texto repetido: {key}")
ALL.update(TEXTOS_ESTUDIO)


def entry(text):
    names = re.findall(r"\{(\w+)\}", text)
    if not names:
        return {"message": text}
    message = text
    placeholders = {}
    for i, name in enumerate(dict.fromkeys(names), 1):
        message = message.replace("{" + name + "}", f"${name.upper()}$")
        placeholders[name] = {"content": f"${i}"}
    return {"message": message, "placeholders": placeholders}


OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(json.dumps({k: entry(v) for k, v in ALL.items()}, ensure_ascii=False, indent=2) + "\n")
print("  ", OUT.relative_to(ROOT), f"({len(ALL)} textos)")
